import fs from 'node:fs/promises';
import path from 'node:path';
import prettier from 'prettier';

const root = path.resolve(import.meta.dirname, '..');
const { palettes, common, aliases } = JSON.parse(
  await fs.readFile(path.join(root, 'src/tokens/contract.json'), 'utf8'),
);
const prettierOptions = await prettier.resolveConfig(path.join(root, 'package.json'));
const format = (source, parser) => prettier.format(source, { ...prettierOptions, parser });
function resolveDefault(value) {
  const resolved = value.replace(/var\((--[\w-]+)\)/g, (_, name) =>
    resolveDefault(common[name] ?? palettes.light[name]),
  );
  const product = resolved.match(/^calc\(([\d.]+)(rem|px) \* ([\d.]+)\)$/);
  return product ? `${Number(product[1]) * Number(product[3])}${product[2]}` : resolved;
}
const block = (selector, values) =>
  `${selector} {\n${Object.entries(values)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n')}\n}\n`;
const css = await format(
  [
    '/* Generated by pnpm tokens:generate from src/tokens/contract.json. */',
    block(":root,\n[data-ec-theme='light']", palettes.light),
    block(".dark,\n[data-ec-theme='dark']", palettes.dark),
    block(
      ":root[data-color-theme='black-gold'],\n[data-ec-color-theme='black-gold']",
      palettes.blackGold,
    ),
    block(
      ':root',
      Object.fromEntries(Object.entries(common).filter(([, value]) => !value.includes('var('))),
    ),
    block(
      ':root,\n[data-ec-theme]',
      Object.fromEntries(Object.entries(common).filter(([, value]) => value.includes('var('))),
    ),
    block("[data-ec-density='comfortable']", { '--ec-density-scale': '1' }),
    block("[data-ec-density='compact']", { '--ec-density-scale': '0.875' }),
    '@media (prefers-reduced-motion: reduce) { *, *::before, *::after { animation-duration: 1ms !important; animation-iteration-count: 1 !important; animation-delay: 0ms !important; transition: none !important; scroll-behavior: auto !important; } }',
  ].join('\n'),
  'css',
);
const defaults = {
  color: Object.fromEntries(
    Object.entries({
      primary: '--primary',
      background: '--background',
      surface: '--surface',
      text: '--foreground',
      success: '--success',
      warning: '--warning',
      danger: '--danger',
    }).map(([name, token]) => [name, palettes.light[token]]),
  ),
  spacing: Object.fromEntries(
    Object.entries(common)
      .filter(([name]) => name.startsWith('--ec-space-'))
      .map(([name, value]) => [name.slice(11), value]),
  ),
  typography: {
    size: Object.fromEntries(
      Object.entries(common)
        .filter(([name]) => name.startsWith('--ec-font-size-'))
        .map(([name, value]) => [name.slice(15), value]),
    ),
  },
  radius: Object.fromEntries(
    Object.entries(common)
      .filter(([name]) => name.startsWith('--ec-radius-'))
      .map(([name, value]) => [name.slice(12), resolveDefault(value)]),
  ),
  size: Object.fromEntries(
    Object.entries(common)
      .filter(([name]) => name.startsWith('--ec-control-'))
      .map(([name, value]) => [name.slice(13), value.match(/^calc\(([^ ]+)/)?.[1] ?? value]),
  ),
  motion: Object.fromEntries(
    Object.entries(palettes.light)
      .filter(([name]) => name.startsWith('--motion-'))
      .map(([name, value]) => [name.slice(9), value]),
  ),
  zIndex: {
    base: 0,
    ...Object.fromEntries(
      Object.entries(common)
        .filter(([name]) => name.startsWith('--ec-z-'))
        .map(([name, value]) => [name.slice(7), Number(value)]),
    ),
  },
  touchTarget: common['--ec-touch-target'],
};
const tokens = await format(
  `// Generated by pnpm tokens:generate from contract.json.\nexport const easecationTokens = ${JSON.stringify(palettes)} as const;\nexport type EaseCationColorToken = keyof typeof easecationTokens.light;\nexport const publicTokenDefaults = ${JSON.stringify(common)} as const;\nexport type DesignTokenName = keyof typeof publicTokenDefaults;\nexport const tokenAliases = ${JSON.stringify(aliases)} as const;\nexport const defaultTokens = ${JSON.stringify(defaults)} as const;\n`,
  'typescript',
);
for (const [relative, content] of [
  ['src/styles/tokens.css', css],
  ['src/tokens/easecation.ts', tokens],
]) {
  const target = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if ((await fs.readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== content)
      throw new Error(`${relative} is stale; run pnpm tokens:generate.`);
  } else await fs.writeFile(target, content);
}
console.log(
  process.argv.includes('--check')
    ? 'Generated tokens are current.'
    : 'Generated CSS and typed tokens.',
);
